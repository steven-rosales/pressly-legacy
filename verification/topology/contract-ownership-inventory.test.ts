const readJson = (relativePath: string): unknown =>
  JSON.parse(readFileSync(`${repositoryRoot}/${relativePath}`, 'utf8'));

const isPackageManifest = (
  value: unknown,
): value is Readonly<{ exports: Readonly<Record<string, unknown>> }> =>
  typeof value === 'object' &&
  value !== null &&
  'exports' in value &&
  typeof value.exports === 'object' &&
  value.exports !== null;

describe('contract ownership inventory', () => {
  it('pins the retired central suite coverage transferred to owner proofs', () => {
    expect(Object.keys(centralTestInventory)).toHaveLength(16);

    const coverage = Object.values(centralTestInventory).reduce(
      (total, suite) => ({
        direct: total.direct + suite.direct,
        table: total.table + suite.table,
      }),
      { direct: 0, table: 0 },
    );

    expect(coverage).toEqual({ direct: 114, table: 8 });
  });

  it('pins every released owner contract export subpath', () => {
    for (const [manifestPath, expectedExports] of Object.entries(
      ownerExportInventory,
    )) {
      const manifest = readJson(manifestPath);
      expect(isPackageManifest(manifest), manifestPath).toBe(true);
      if (!isPackageManifest(manifest)) continue;
      expect(Object.keys(manifest.exports).sort(), manifestPath).toEqual(
        [...expectedExports].sort(),
      );
    }
  });
});
